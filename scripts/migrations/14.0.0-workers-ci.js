#!/usr/bin/env node
/*
Purpose: Move a consumer to the 14.0.0 contract: flat identity params in
  hugo.yml, Worker/Wrangler config generated by the engine and one CI stub.
Run from: Consumer root through `sh do update`; --check reports without writing.
Writes: hugo.yml params (comments preserved), .gitignore, and deletes only the
  recognized engine-owned files (worker.js, wrangler.workers.toml and the three
  legacy workflows). Custom files are kept and reported. Pages/Netlify configs
  stay until their hosting is retired (manual step in MIGRATIONS.md).
*/
import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { pathToFileURL } from 'node:url'
import { parseDocument } from 'yaml'

const WORKER_NAME = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/
const REMOVED_PARAMS = ['name', 'netlify_id', 'netlify_hook', 'cloudflare_id']
// Engine-owned files and a marker that proves each is the stock version.
const OWNED_FILES = [
  ['worker.js', source => /^import \{ createFormsWorker \} from '\.\/(?:core|themes\/sansoul)\/forms\/worker\.js'$/m.test(source) && !/createCommerceWorker/.test(source)],
  ['wrangler.workers.toml', source => /^main = "worker\.js"$/m.test(source)],
  ['.github/workflows/deploy-workers.yml', source => /wrangler@[\d.]+ deploy --config wrangler\.workers\.toml/.test(source)],
  ['.github/workflows/backup.yml', source => /(?:core|themes\/sansoul)\/scripts\/mirror-to-gitlab\.sh/.test(source)],
  ['.github/workflows/forms-dispatch.yml', source => /\/api\/forms\/admin\/dispatch/.test(source)]
]

export function migrateProject (projectDir, { check = false } = {}) {
  const changed = []
  const removed = []
  const warnings = []

  // 1. hugo.yml: flat params, derived domain and Worker vars.
  const hugoFile = path.join(projectDir, 'hugo.yml')
  const source = fs.readFileSync(hugoFile, 'utf8')
  const doc = parseDocument(source)
  if (doc.errors.length) throw new Error(`hugo.yml: ${doc.errors[0].message}`)
  const params = doc.get('params', true) || doc.createNode({})
  const get = key => {
    const value = params.get(key)
    return value === undefined || value === null ? '' : String(value).trim()
  }
  const remote = githubRemote(projectDir)
  const cmsRepo = cmsRepository(projectDir)
  const owner = get('owner') || remote?.owner || cmsRepo?.owner || ''
  const repo = get('repo') || remote?.repo || cmsRepo?.repo || get('domain')
  let host = ''
  try { host = new URL(String(doc.get('baseURL') || '')).host } catch {}
  if (!owner || !repo) warnings.push('Could not infer params.owner/params.repo; set them in hugo.yml.')
  if (owner && !get('owner')) params.set('owner', owner)
  if (repo && !get('repo')) params.set('repo', repo)
  const deployed = wranglerName(projectDir)
  if (deployed && !get('worker') && deployed !== repo.toLowerCase()) params.set('worker', deployed)
  else if (repo && !get('worker') && !WORKER_NAME.test(repo.toLowerCase())) {
    const legacy = get('name').toLowerCase()
    const worker = WORKER_NAME.test(legacy) ? legacy : repo.toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 63)
    params.set('worker', worker)
    warnings.push(`params.worker = ${worker} (the repository name is not a valid Worker name); check it before the first deploy.`)
  }
  if (get('netlify_id') && !get('netlify') && WORKER_NAME.test(get('name'))) params.set('netlify', get('name'))
  if (get('domain') && get('domain') === host) params.delete('domain')
  for (const key of REMOVED_PARAMS) params.delete(key)

  const vars = wranglerVars(projectDir)
  if (Object.keys(vars).length && !params.get('worker_vars')) params.set('worker_vars', vars)
  if (!doc.get('params')) doc.set('params', params)
  const nextHugo = doc.toString({ lineWidth: 0 })
  if (nextHugo !== source) {
    changed.push('hugo.yml')
    if (!check) fs.writeFileSync(hugoFile, nextHugo)
  }

  // 2. Engine-owned files now generated under worker/ or by core/ci/run.
  for (const [file, isStock] of OWNED_FILES) {
    const target = path.join(projectDir, file)
    if (!fs.existsSync(target)) continue
    if (!isStock(fs.readFileSync(target, 'utf8'))) {
      warnings.push(`${file} is customized; it was kept. Move its logic to the engine or remove it by hand.`)
      continue
    }
    removed.push(file)
    if (!check) fs.rmSync(target)
  }

  // 3. worker/ is fully generated; local Worker state and secrets stay out of Git.
  const ignoreFile = path.join(projectDir, '.gitignore')
  const ignore = fs.existsSync(ignoreFile) ? fs.readFileSync(ignoreFile, 'utf8') : ''
  const lines = ignore.split('\n').filter(line => line.trim() !== 'worker/forms.generated.js')
  while (lines.length && lines.at(-1) === '') lines.pop()
  for (const entry of ['/worker/', '.wrangler', '.dev.vars']) {
    if (!lines.some(line => line.trim() === entry)) lines.push(entry)
  }
  const nextIgnore = lines.join('\n') + '\n'
  if (nextIgnore !== ignore) {
    changed.push('.gitignore')
    if (!check) fs.writeFileSync(ignoreFile, nextIgnore)
  }

  for (const file of ['wrangler.toml', 'netlify.toml']) {
    if (fs.existsSync(path.join(projectDir, file))) warnings.push(`${file} still serves the old hosting; delete it once the Workers deploy is verified and that hosting is retired.`)
  }
  return { changed, removed, warnings }
}

function githubRemote (projectDir) {
  const result = spawnSync('git', ['-C', projectDir, 'remote', 'get-url', 'origin'], { encoding: 'utf8' })
  const match = /github\.com[/:]([^/]+)\/([^/]+?)(?:\.git)?\/?$/.exec(result.stdout.trim())
  return match ? { owner: match[1], repo: match[2] } : null
}

function cmsRepository (projectDir) {
  const file = path.join(projectDir, 'data', 'config.yml')
  if (!fs.existsSync(file)) return null
  const value = parseDocument(fs.readFileSync(file, 'utf8')).get('cms_repo')
  const match = /^([^/\s]+)\/([^/\s]+)$/.exec(String(value || ''))
  return match ? { owner: match[1], repo: match[2] } : null
}

// Name of the Worker already deployed from the former wrangler.workers.toml.
function wranglerName (projectDir) {
  const file = path.join(projectDir, 'wrangler.workers.toml')
  if (!fs.existsSync(file)) return ''
  const name = /^name = "([^"]+)"$/m.exec(fs.readFileSync(file, 'utf8'))?.[1] || ''
  return WORKER_NAME.test(name) ? name : ''
}

// [vars] of the former wrangler.workers.toml: simple `KEY = "value"` lines only.
function wranglerVars (projectDir) {
  const file = path.join(projectDir, 'wrangler.workers.toml')
  if (!fs.existsSync(file)) return {}
  const vars = {}
  let inVars = false
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const header = /^\s*\[([^\]]+)\]\s*$/.exec(line)
    if (header) { inVars = header[1].trim() === 'vars'; continue }
    const entry = inVars && /^\s*([A-Z][A-Z0-9_]*)\s*=\s*"([^"]*)"\s*(?:#.*)?$/.exec(line)
    if (entry) vars[entry[1]] = entry[2]
  }
  return vars
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const check = process.argv.includes('--check')
  const result = migrateProject(process.cwd(), { check })
  const verb = check ? 'Would' : 'Did'
  console.log(`${verb} update: ${result.changed.join(', ') || 'nothing'}; ${verb.toLowerCase()} remove: ${result.removed.join(', ') || 'nothing'}.`)
  for (const warning of result.warnings) console.warn(`Review: ${warning}`)
}
