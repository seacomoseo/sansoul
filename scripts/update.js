#!/usr/bin/env node

/*
Purpose: Safely update one SanSoul consumer, its automatic migrations, generated
  root documentation, and compatibility version.
Run from: Consumer project root through `sh do update [--check]`.
Writes: The SanSoul submodule checkout, documented migration targets, generated
  README.md/AGENTS.md, and the root package version after validation.
*/

import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { spawnSync } from 'node:child_process'
import { createInterface } from 'node:readline/promises'

const projectDir = process.cwd()
const themeDir = path.join(projectDir, 'themes', 'sansoul')
const args = process.argv.slice(2)
const checkOnly = args.includes('--check')
const knownArgs = new Set(['--check', '--help'])
const rootDocsMarker = '<!-- Generated by `sh do root-docs`'
const migrationScripts = {
  '6.0.0': ['6.0.0-explicit-booleans.js'],
  '6.0.1': ['6.0.1-sharp.js'],
  '6.0.2': ['6.0.2-remove-legacy-css.js'],
  '7.0.0': ['7.0.0-content-adapters.js']
}
const registeredMigrationVersions = new Set([
  ...Object.keys(migrationScripts),
  '5.1.0',
  '5.1.1',
  '5.1.3'
])
const supportedManualMigrations = new Set([
  '5.1.0',
  '5.1.1',
  '5.1.3',
  '6.0.0',
  '6.0.1',
  '6.0.2',
  '7.0.0'
])

await main()

async function main () {
  validateArguments()
  if (args.includes('--help')) {
    console.log('Usage: sh do update [--check]')
    console.log('  --check  Fetch remote metadata and run all preflight checks without updating files.')
    return
  }
  validateRepositoryLayout()
  const preupdatedSubmodule = assertCleanProjectTree()
  assertCleanTree('SanSoul submodule', themeDir)
  assertNoGitOperation(projectDir)
  assertNoGitOperation(themeDir)

  const rootPackage = readJson(path.join(projectDir, 'package.json'), 'root package.json')
  const rootVersion = parseVersion(rootPackage.version, 'root package version')
  const rootLockPath = path.join(projectDir, 'package-lock.json')
  if (fs.existsSync(rootLockPath)) readJson(rootLockPath, 'root package-lock.json')

  validateManagedRootDocs()

  const oldThemeCommit = git(themeDir, ['rev-parse', 'HEAD'])
  const rootThemeCommit = git(projectDir, ['rev-parse', 'HEAD:themes/sansoul'])
  if (oldThemeCommit !== rootThemeCommit && (!preupdatedSubmodule || !isAncestor(rootThemeCommit, oldThemeCommit))) {
    fail('The SanSoul checkout does not match the project gitlink by a clean fast-forward. Restore the recorded submodule first, then retry.')
  }

  const branch = configuredBranch()
  console.log(`Fetching SanSoul branch ${branch} (this updates Git metadata, not project files).`)
  git(themeDir, ['fetch', '--quiet', 'origin', branch])
  const targetCommit = git(themeDir, ['rev-parse', `refs/remotes/origin/${branch}`])
  const targetPackage = readJsonFromGit(targetCommit, 'package.json', 'target theme package.json')
  const targetVersion = parseVersion(targetPackage.version, 'target theme package version')
  const oldThemePackage = readJson(path.join(themeDir, 'package.json'), 'installed theme package.json')
  const oldThemeVersion = parseVersion(oldThemePackage.version, 'installed theme package version')

  if (compareVersions(targetVersion, oldThemeVersion) < 0) {
    fail(`Remote SanSoul ${targetVersion.raw} is older than the installed ${oldThemeVersion.raw}; refusing to move backwards.`)
  }
  if (compareVersions(rootVersion, oldThemeVersion) > 0) {
    fail(`The project records ${rootVersion.raw}, newer than the currently installed SanSoul ${oldThemeVersion.raw}. Resolve the inconsistent versions before updating.`)
  }
  if (compareVersions(rootVersion, targetVersion) > 0) {
    fail(`The project records ${rootVersion.raw}, newer than remote SanSoul ${targetVersion.raw}.`)
  }
  if (!isAncestor(oldThemeCommit, targetCommit)) {
    fail('The installed SanSoul commit and remote branch have diverged. No files were changed; resolve the submodule history manually.')
  }

  const migrationsSource = git(themeDir, ['show', `${targetCommit}:MIGRATIONS.md`])
  const migrations = parseMigrations(migrationsSource)
  const pending = migrations.filter(migration =>
    compareVersions(migration.version, rootVersion) > 0 &&
    compareVersions(migration.version, targetVersion) <= 0
  )

  validateMigrationSupport(pending, targetCommit, rootVersion)
  validateMigrationConflicts(pending)
  validateTargetTemplates(targetCommit)
  validateNpmAvailability(pending, rootLockPath)

  printPlan({
    branch,
    oldThemeCommit,
    targetCommit,
    oldThemeVersion,
    rootVersion,
    targetVersion,
    pending
  })

  if (checkOnly) {
    console.log('\nPreflight passed. --check did not change project files or the checked-out theme commit.')
    return
  }

  if (targetCommit !== oldThemeCommit) {
    console.log('\nUpdating the SanSoul checkout…')
    git(themeDir, ['checkout', '--detach', targetCommit])
  } else {
    console.log('\nSanSoul is already at the remote commit.')
  }

  for (const migration of pending) {
    for (const script of migrationScripts[migration.version.raw] || []) {
      run(process.execPath, [path.join(themeDir, 'scripts', 'migrations', script)], projectDir)
    }
  }

  run('sh', ['do', 'root-docs'], projectDir)

  if (migrationRequiresNpmInstall(pending) && fs.existsSync(rootLockPath)) {
    run('npm', ['install'], projectDir)
  }

  console.log('\nBuilding the updated consumer project…')
  run('sh', ['do', 'hugo'], projectDir)

  if (pending.length === 0) {
    run(process.execPath, [path.join(themeDir, 'scripts', 'migrations.js'), 'mark', '--yes'], projectDir)
    console.log('\nUpdate and build completed. The root package version now matches SanSoul.')
    return
  }

  const migrationsCommand = [process.execPath, path.join(themeDir, 'scripts', 'migrations.js'), 'show']
  run(migrationsCommand[0], migrationsCommand.slice(1), projectDir)

  if (await confirmManualValidations()) {
    run(process.execPath, [path.join(themeDir, 'scripts', 'migrations.js'), 'mark', '--yes'], projectDir)
    console.log('\nUpdate completed and the compatibility version was synchronized.')
  } else {
    console.log('\nThe theme and automatic migrations are updated. Complete the listed project-specific checks, then run `sh do migrations mark --yes`.')
  }
}

function validateArguments () {
  const unknown = args.filter(argument => !knownArgs.has(argument))
  if (unknown.length > 0) fail(`Unknown option: ${unknown.join(', ')}. Use only --check.`)
}

function validateRepositoryLayout () {
  const root = git(projectDir, ['rev-parse', '--show-toplevel'])
  if (path.resolve(root) !== path.resolve(projectDir)) {
    fail('Run `sh do update` from the project root.')
  }
  if (!fs.existsSync(path.join(projectDir, '.gitmodules')) || !fs.existsSync(themeDir)) {
    fail('SanSoul is not initialized at themes/sansoul. Initialize the declared submodule, then retry.')
  }
  if (!fs.existsSync(path.join(projectDir, 'do'))) fail('Missing root `do` wrapper.')
  const submodulePath = git(projectDir, ['config', '-f', '.gitmodules', '--get', 'submodule.themes/sansoul.path'], { allowFailure: true })
  if (submodulePath !== 'themes/sansoul') {
    fail('.gitmodules does not declare themes/sansoul; refusing to update an unexpected path.')
  }
}

function assertCleanTree (label, directory) {
  const status = git(directory, ['status', '--porcelain=v1', '--untracked-files=all'])
  if (status) {
    fail(`The ${label} working tree has local changes. No project files were changed. Commit or stash them, then retry:\n${status}`)
  }
}

function assertCleanProjectTree () {
  const status = git(projectDir, ['status', '--porcelain=v1', '--untracked-files=all'])
  const lines = status ? status.split('\n') : []
  const submoduleAdvance = lines.filter(line => line.slice(0, 2) === ' M' && line.slice(3) === 'themes/sansoul')
  const otherChanges = lines.filter(line => !submoduleAdvance.includes(line))
  if (otherChanges.length > 0) {
    fail(`The project working tree has local changes. No project files were changed. Commit or stash them, then retry:\n${otherChanges.join('\n')}`)
  }
  return submoduleAdvance.length === 1
}

function assertNoGitOperation (directory) {
  const operationFiles = ['MERGE_HEAD', 'CHERRY_PICK_HEAD', 'REVERT_HEAD', 'rebase-apply', 'rebase-merge']
  const gitDir = git(directory, ['rev-parse', '--absolute-git-dir'])
  for (const name of operationFiles) {
    if (fs.existsSync(path.join(gitDir, name))) fail(`Git has an unfinished operation (${name}) in ${directory}. Finish or abort it before updating.`)
  }
  if (fs.existsSync(path.join(gitDir, 'index.lock'))) fail(`Git has an active index lock in ${directory}; wait for the Git operation to finish before updating.`)
}

function configuredBranch () {
  const branch = git(projectDir, ['config', '-f', '.gitmodules', '--get', 'submodule.themes/sansoul.branch'], { allowFailure: true })
  if (!branch) {
    fail('No branch is configured for themes/sansoul in .gitmodules. Set its branch explicitly before updating.')
  }
  if (git(themeDir, ['check-ref-format', '--branch', branch], { allowFailure: true }) !== branch) {
    fail(`Invalid SanSoul branch in .gitmodules: ${branch}`)
  }
  if (!git(themeDir, ['remote'], { allowFailure: true }).split('\n').includes('origin')) {
    fail('The SanSoul submodule has no origin remote.')
  }
  return branch
}

function validateManagedRootDocs () {
  for (const file of ['README.md', 'AGENTS.md']) {
    const target = path.join(projectDir, file)
    if (!fs.existsSync(target)) continue
    const source = fs.readFileSync(target, 'utf8')
    if (!source.startsWith(rootDocsMarker)) {
      fail(`${file} is not generated by SanSoul. No update was applied; preserve its content and resolve it with sh do root-docs before retrying.`)
    }
  }
}

function validateMigrationSupport (pending, targetCommit, rootVersion) {
  if (compareVersions(rootVersion, parseVersion('5.0.0', 'legacy baseline')) < 0) {
    fail('This project predates the 5.0.0 baseline. The safe updater will not run the legacy migration chain or move the submodule.')
  }

  for (const migration of pending) {
    const version = migration.version.raw
    if (version === '5.0.0') {
      fail('This project still needs the verified 5.0.0 baseline migration. No files were changed.')
    }
    if (!registeredMigrationVersions.has(version)) {
      fail(`Migration ${version} has no updater policy. No files were changed; add an explicit automation or manual-review entry before this version can be applied.`)
    }
    const registeredScripts = migrationScripts[version] || []
    const documentedScripts = [...migration.content.matchAll(/themes\/sansoul\/scripts\/migrations\/([A-Za-z0-9._-]+\.js)/g)]
      .map(match => match[1])
      .filter((script, index, all) => all.indexOf(script) === index)
    const unregisteredScripts = documentedScripts.filter(script => !registeredScripts.includes(script))
    const undocumentedScripts = registeredScripts.filter(script => !documentedScripts.includes(script))
    if (unregisteredScripts.length > 0 || undocumentedScripts.length > 0) {
      fail(`Migration ${version} automation and its updater policy do not match. Documented but unregistered: ${unregisteredScripts.join(', ') || 'none'}; registered but undocumented: ${undocumentedScripts.join(', ') || 'none'}. No project files were changed.`)
    }
    for (const script of registeredScripts) {
      git(themeDir, ['cat-file', '-e', `${targetCommit}:scripts/migrations/${script}`])
    }
  }
}

function validateMigrationConflicts (pending) {
  if (!pending.some(migration => migration.version.raw === '7.0.0')) return
  const contentDir = path.join(projectDir, 'content')
  if (!fs.existsSync(contentDir)) return

  const conflicts = []
  for (const name of fs.readdirSync(contentDir)) {
    if (!/^values\.[^.]+\.ya?ml$/.test(name)) continue
    const target = name.replace(/^values\./, 'global.')
    if (fs.existsSync(path.join(contentDir, target))) conflicts.push(`${path.join('content', name)} → ${path.join('content', target)}`)
  }

  if (conflicts.length > 0) {
    fail(`The 7.0.0 content rename would overwrite existing files. No update was applied:\n${conflicts.map(item => `- ${item}`).join('\n')}`)
  }
}

function validateTargetTemplates (targetCommit) {
  for (const file of ['templates/root/README.md', 'templates/root/AGENTS.md']) {
    git(themeDir, ['cat-file', '-e', `${targetCommit}:${file}`])
  }
}

function validateNpmAvailability (pending, lockPath) {
  if (!fs.existsSync(lockPath) || !migrationRequiresNpmInstall(pending)) return
  const result = spawnSync('npm', ['--version'], { cwd: projectDir, encoding: 'utf8' })
  if (result.error || result.status !== 0) {
    const versions = pending.filter(migration => /`npm install`/.test(migration.content)).map(migration => migration.version.raw)
    fail(`Migration ${versions.join(', ')} needs npm to synchronize the existing package-lock.json. Install Node.js/npm before updating.`)
  }
}

function migrationRequiresNpmInstall (pending) {
  return pending.some(migration => /`npm install`/.test(migration.content))
}

function printPlan ({ branch, oldThemeCommit, targetCommit, oldThemeVersion, rootVersion, targetVersion, pending }) {
  console.log('SanSoul update preflight')
  console.log(`- Theme: ${oldThemeVersion.raw} (${short(oldThemeCommit)}) → ${targetVersion.raw} (${short(targetCommit)})`)
  console.log(`- Remote branch: ${branch}`)
  console.log(`- Root compatibility version: ${rootVersion.raw}`)
  console.log(`- Root README.md and AGENTS.md: safe to regenerate from the target theme templates`)
  if (pending.length === 0) {
    console.log('- Consumer migrations: none documented for this version range')
  } else {
    console.log(`- Consumer migrations: ${pending.map(item => item.version.raw).join(', ')}`)
    for (const migration of pending) {
      const scripts = migrationScripts[migration.version.raw] || []
      if (scripts.length > 0) console.log(`  - ${migration.version.raw}: ${scripts.join(', ')}`)
      if (supportedManualMigrations.has(migration.version.raw)) console.log(`  - ${migration.version.raw}: project-specific review remains after automatic steps`)
    }
  }
  console.log('- Validation: run the project build before synchronizing package.json')
}

async function confirmManualValidations () {
  if (!process.stdin.isTTY || !process.stdout.isTTY) {
    console.log('\nManual migration checks remain. This non-interactive run will leave the compatibility version unchanged.')
    return false
  }

  const terminal = createInterface({ input: process.stdin, output: process.stdout })
  try {
    const answer = await terminal.question('\nHave you completed every project-specific validation listed above? Type yes to synchronize package.json: ')
    return answer.trim().toLowerCase() === 'yes'
  } finally {
    terminal.close()
  }
}

function parseMigrations (source) {
  const headings = [...source.matchAll(/^## (\d+\.\d+\.\d+)(?:\s+.*)?$/gm)]
  return headings.map((heading, index) => {
    const start = heading.index
    const end = headings[index + 1]?.index ?? source.length
    return {
      version: parseVersion(heading[1], 'migration heading'),
      content: source.slice(start, end)
    }
  }).sort((left, right) => compareVersions(left.version, right.version))
}

function readJson (file, label) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'))
  } catch (error) {
    fail(`Cannot read ${label}: ${error.message}`)
  }
}

function readJsonFromGit (commit, file, label) {
  try {
    return JSON.parse(git(themeDir, ['show', `${commit}:${file}`]))
  } catch (error) {
    fail(`Cannot read ${label}: ${error.message}`)
  }
}

function parseVersion (value, label) {
  const match = /^(\d+)\.(\d+)\.(\d+)$/.exec(value || '')
  if (!match) fail(`Invalid ${label}: ${value}. Expected x.y.z.`)
  return { raw: value, parts: match.slice(1).map(Number) }
}

function compareVersions (left, right) {
  for (let index = 0; index < 3; index++) {
    if (left.parts[index] !== right.parts[index]) return left.parts[index] - right.parts[index]
  }
  return 0
}

function isAncestor (ancestor, descendant) {
  const result = spawnSync('git', ['-C', themeDir, 'merge-base', '--is-ancestor', ancestor, descendant], { encoding: 'utf8' })
  if (result.status === 0) return true
  if (result.status === 1) return false
  fail(result.stderr.trim() || 'Git could not compare the installed and remote SanSoul commits.')
}

function git (directory, args, { allowFailure = false } = {}) {
  const result = spawnSync('git', ['-C', directory, ...args], { encoding: 'utf8' })
  if (result.error || (result.status !== 0 && !allowFailure)) {
    fail(result.error?.message || result.stderr.trim() || `git ${args.join(' ')} failed.`)
  }
  // Git porcelain uses leading spaces as status data; preserve them.
  return result.status === 0 ? result.stdout.replace(/\r?\n$/, '') : ''
}

function run (command, args, cwd) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit' })
  if (result.error) fail(`Could not run ${command}: ${result.error.message}`)
  if (result.status !== 0) fail(`${command} ${args.join(' ')} failed with exit code ${result.status}. The update may be partially applied; inspect both Git working trees before retrying.`)
}

function short (commit) {
  return commit.slice(0, 12)
}

function fail (message) {
  console.error(`SanSoul update stopped: ${message}`)
  process.exit(2)
}
