#!/bin/sh
# Run from a clean SanSoul consumer root. Keep its engine path and package manager.
set -eu

fail() {
  printf 'SanSoul: %s\n' "$*" >&2
  exit 1
}

test -f .gitmodules && test -f package.json && test -f do &&
  test -z "$(git rev-parse --show-prefix)" ||
  fail 'Ejecuta el comando desde la raíz del proyecto.'

version=$(node -p 'require("./package.json").version || ""')
case "$version" in
  [0-4].*) fail 'Este proyecto necesita primero su actualización legada. Pásame esta salida.' ;;
esac

test -z "$(git status --porcelain --ignore-submodules=none)" ||
  fail 'Guarda o confirma los cambios del proyecto y del submódulo antes de reintentar.'
test ! -d .sansoul-dev.lock ||
  fail 'Detén el servidor local de este proyecto y vuelve a ejecutar el mismo comando.'

engine=
section=
for candidate in themes/sansoul core; do
  keys=$(git config -f .gitmodules --get-regexp '^submodule\..*\.path$' |
    awk -v candidate="$candidate" '$NF == candidate {sub(/\.path[[:space:]].*$/, ""); print}')
  if test -n "$keys"; then
    test -z "$engine" || fail 'Hay más de una ruta de SanSoul declarada.'
    engine=$candidate
    section=$keys
  fi
done
test -n "$engine" || fail 'No encuentro el submódulo de SanSoul.'
case "$(git config -f .gitmodules --get "$section.url")" in
  https://github.com/seacomoseo/sansoul.git|https://github.com/seacomoseo/sansoul|git@github.com:seacomoseo/sansoul.git) ;;
  *) fail 'El proyecto usa un origen de SanSoul personalizado. Pásame esta salida.' ;;
esac
branch=$(git config -f .gitmodules --get "$section.branch" || :)
test -z "$branch" || test "$branch" = main || fail 'El submódulo usa una rama distinta de main. Pásame esta salida.'

for document in README.md AGENTS.md; do
  if test -e "$document" && ! head -n 1 "$document" | grep -Fq '<!-- Generated by `sh do root-docs`'; then
    fail "$document contiene documentación propia. Pásame esta salida para preservarla."
  fi
done

git submodule update --init -- "$engine"
case "$(git -C "$engine" config --get remote.origin.url)" in
  https://github.com/seacomoseo/sansoul.git|https://github.com/seacomoseo/sansoul|git@github.com:seacomoseo/sansoul.git) ;;
  *) fail 'El checkout local del motor usa otro origen. Pásame esta salida.' ;;
esac
previous=$(git -C "$engine" rev-parse HEAD)
previous_branch=$(git -C "$engine" symbolic-ref --quiet --short HEAD || :)
git -C "$engine" fetch --quiet origin main
target=$(git -C "$engine" rev-parse refs/remotes/origin/main)
git -C "$engine" merge-base --is-ancestor "$previous" "$target" ||
  fail 'El historial del motor ha divergido de main. Pásame esta salida.'
git -C "$engine" cat-file -e "$target:scripts/update.js" ||
  fail 'El motor remoto no contiene el actualizador.'

scratch=$(mktemp -d)
trap 'rm -rf -- "$scratch"' 0
if ! node -e 'process.exit(/^2\./.test(require("yaml/package.json").version) ? 0 : 1)' 2>/dev/null; then
  npm install --prefix "$scratch" --no-save --no-package-lock --no-audit --no-fund --ignore-scripts yaml@2.9.1
  export NODE_PATH="$scratch/node_modules${NODE_PATH:+:$NODE_PATH}"
fi

if test "$previous" != "$target"; then
  git -C "$engine" checkout --quiet --detach "$target"
fi
if ! sh "$engine/do" update --check; then
  if test "$previous" != "$target" && test -z "$(git -C "$engine" status --porcelain)"; then
    if test -n "$previous_branch"; then
      git -C "$engine" checkout --quiet "$previous_branch"
    else
      git -C "$engine" checkout --quiet --detach "$previous"
    fi
  fi
  fail 'La comprobación previa se detuvo. Pásame la salida anterior.'
fi

sh "$engine/do" update
