import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { spawnSync } from 'node:child_process'

test('CMS media inheritance, custom i18n and config visual groups retain flat stored fields', async t => {
  if (spawnSync('hugo', ['version']).status !== 0) return t.skip('Hugo unavailable')
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'sansoul-cms-authoring-'))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  await fs.mkdir(path.join(root, 'layouts'), { recursive: true })
  await fs.cp(new URL('../../layouts/partials', import.meta.url), path.join(root, 'layouts/partials'), { recursive: true })
  await fs.cp(new URL('../../data', import.meta.url), path.join(root, 'data'), { recursive: true })
  await fs.writeFile(path.join(root, 'hugo.yml'), 'baseURL: https://fixture.example/\nlanguageCode: es\n')
  await fs.writeFile(path.join(root, 'layouts/index.html'), `{{ $t := hugo.Data.cms.es }}{{ $media := slice }}{{ range slice "img" "vid" "vimg" "file" }}{{ $media = $media | append (partial "cms/field" (dict "name" . "widget" .)) }}{{ end }}{{ dict "media" $media "emptySelect" (partial "cms/field" (dict "name" "choice" "widget" "select" "opts" slice)) "markdown" (partial "cms/field" (dict "name" "body" "widget" "md" "show_raw" false)) "limitedFile" (partial "cms/field" (dict "name" "asset" "widget" "img" "max_file_size" 1234)) "color" (partial "cms/field" (dict "name" "color" "widget" "color" "allow_input" false)) "nativeSelect" (partial "cms/field" (dict "name" "choice" "widget" "select" "opts" (slice "a" "b"))) "hidden" (partial "cms/field" (dict "name" "meta" "widget" "hide")) "multipleMedia" (partial "cms/field" (dict "name" "imgs" "widget" "vimg" "multi" true)) "explicit" (partial "cms/field" (dict "name" "img" "widget" "img" "i18n" false)) "boxes" (partial "cms/config/boxes" $t) "blocks" (partial "cms/config/blocks" $t) "options" (partial "cms/config/options" $t) "global" (partial "cms/config/singletons/global" $t) "config" (partial "cms/config/collections/files/config" $t) "customsSchema" (partial "cms/config/collections/files/customs" $t) "custom" (partial "cms/config/collections/customs" (dict "name" "outer" "widget" "object" "accumulated" (slice (dict "name" "prior" "widget" "string")) "fields" (slice (dict "name" "nested" "widget" "object" "fields" (slice (dict "name" "value" "widget" "string" "i18n" false) (dict "name" "flag" "widget" "bool" "def" false) (dict "name" "count" "widget" "int" "def" 0)))) "t" $t)) | jsonify | safeHTML }}`)
  const run = spawnSync('hugo', [], { cwd: root, encoding: 'utf8' })
  assert.equal(run.status, 0, run.stderr)
  const result = JSON.parse(await fs.readFile(path.join(root, 'public/index.html'), 'utf8'))
  assert.ok(result.media.every(field => field.i18n === 'duplicate_if_empty'))
  assert.equal(result.explicit.i18n, false)
  assert.equal(result.color.allowInput, false)
  assert.equal(Object.hasOwn(result.color, 'allow_input'), false)
  assert.deepEqual(result.markdown.modes, ['rich_text'])
  assert.equal(Object.hasOwn(result.markdown, 'show_raw'), false)
  assert.equal(result.limitedFile.media_libraries.all.max_file_size, 1234)
  assert.equal(Object.hasOwn(result.limitedFile, 'max_file_size'), false)
  const customAliases = Object.assign({}, ...result.customsSchema)
  const leafOptions = customAliases['&customs_widget_last']['<<'][0].options
  assert.ok(leafOptions.includes('str') && leafOptions.includes('img'))
  assert.ok(!leafOptions.includes('dict') && !leafOptions.includes('slice'))
  assert.deepEqual(result.nativeSelect.options, ['a', 'b'])
  assert.deepEqual(result.emptySelect.options, [])
  assert.equal(Object.hasOwn(result.nativeSelect, 'opts'), false)
  assert.equal(Object.hasOwn(result.hidden, 'required'), false)
  assert.equal(result.multipleMedia.i18n, true)
  assert.equal(result.multipleMedia.multiple, true)
  assert.equal(result.custom[0].name, 'prior')
  assert.equal(result.custom[1].name, 'outer')
  assert.equal(result.custom[1].fields[0].name, 'nested')
  assert.equal(result.custom[1].fields[0].fields[0].name, 'value')
  assert.equal(result.custom[1].fields[0].fields[0].i18n, false)
  assert.equal(result.custom[1].fields[0].fields[1].default, false)
  assert.equal(result.custom[1].fields[0].fields[2].default, 0)
  const globalFields = result.global.find(item => item['&global'])['&global']
  assert.ok(globalFields.find(field => field.name === 'footer').fields.length > 0, 'default footer must use the new fields API')
  const options = result.options['&opts_i18n']
  assert.ok(options.some(option => option.value === 'duplicate_if_empty'))
  assert.ok(options.some(option => option.value === false))
  const fields = result.config.find(item => item['&config'])['&config']
  assert.ok(fields.every(field => !Array.isArray(field)))
  const groups = Object.groupBy(fields.filter(field => field._sansoul_group), field => field._sansoul_group.name)
  assert.deepEqual(groups.google.map(field => field['<<']), ['~config_ga4', '~config_g_site_verify', '~config_g_file_verify', '~config_g_translate'])
  assert.deepEqual(groups.locale.map(field => field['<<']), ['~config_phone_code', '~config_time_zone', '~config_currency'])
  assert.deepEqual(groups.images.map(field => field.name), ['imgs_webp', 'imgs_remote', 'imgs_quality', 'imgs_dpr'])
  assert.deepEqual(groups.cms.map(field => field.name), ['cms_repo', 'cms_logo', 'cms_lang', 'cms_editorial', 'cms_hide'])
  assert.deepEqual(groups.site.map(field => field.name), ['favicon', 'lang_main_subdir', 'cookies_legal', 'ga4_pagespeed_hide', 'dev', 'show'])
  const imageField = name => groups.images.find(field => field.name === name)
  assert.equal(imageField('imgs_quality').min, 1)
  assert.equal(imageField('imgs_quality').max, 100)
  assert.equal(imageField('imgs_quality').default, 60)
  assert.equal(imageField('imgs_dpr').default, 2)
  assert.equal(imageField('imgs_remote').required, false)
  assert.equal(imageField('imgs_remote').default, undefined)
  const aliases = Object.assign({}, ...result.boxes, ...result.blocks)
  for (const key of ['mt', 'mb', 'ml', 'mr']) {
    assert.equal(aliases[`&${key}`].name, key)
    assert.equal(aliases[`&${key}_vl`].name, `${key}_vl`)
    assert.ok(!aliases[`&${key}_vs`])
  }
  for (const key of ['list', 'step', 'gallery', 'faq', 'review', 'geo', 'link', 'form']) {
    assert.ok(aliases[`&${key}`].fields.includes('~mt'), `${key} has an optional base top margin`)
    assert.ok(aliases[`&${key}`].fields.includes('~mt_vl'), `${key} has an optional large top margin`)
  }
  assert.equal(aliases['&ga4'].widget, 'string')
  assert.equal(aliases['&il']['<<'][0].name, 'il')
  assert.equal(aliases['&ir']['<<'][0].name, 'ir')
  assert.ok(aliases['&form'].fields.includes('~ga4'))
  for (const icon of ['~il', '~ir']) assert.ok(aliases['&form'].fields.includes(icon))
  assert.ok(!aliases['&form'].fields.includes('~icon'))
  assert.equal(aliases['&inputs_md'].fields.at(-1).widget, 'markdown')
  assert.deepEqual(aliases['&inputs_md'].fields.at(-1).modes, ['rich_text', 'raw'])
  assert.ok(aliases['&link'].fields.includes('~il'))
  assert.ok(aliases['&link'].fields.includes('~ir'))
  assert.ok(!aliases['&link'].fields.includes('~icon'))
  assert.equal(aliases['&review_il']['<<'][0].name, 'il')
  assert.equal(aliases['&review_ir']['<<'][0].name, 'ir')
  assert.ok(!fields.some(field => ['webp', 'img_sizes', 'development'].includes(field.name)))
})
