const sourceEngine = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const scripts = ['engine-paths.js', 'prebuild-config.js', 'lifecycle.js', 'update.js', 'dependencies.js', 'root-docs.js', 'migrations.js', 'video-metadata.js']
const marker = '<!-- Generated by `sh do root-docs` -->\n'

test('legacy engine cleanup preserves an unrelated core directory', () => {
  const project = fs.mkdtempSync(path.join(os.tmpdir(), 'sansoul-unrelated-core-'))
  try {
    write(project, 'core/prebuild/public/keep.txt', 'unrelated output\n')
    // A directory named do must not qualify as the wrapper's regular file.
    fs.mkdirSync(path.join(project, 'core/do'))
    write(project, 'themes/sansoul/do', '#!/bin/sh\n')
    write(project, 'themes/sansoul/prebuild/public/generated.txt', 'generated\n')
    assert.equal(findEnginePath(project), 'themes/sansoul')
    new Lifecycle({ projectDir: project }).removeGeneratedOutputs()
    assert.equal(fs.readFileSync(path.join(project, 'core/prebuild/public/keep.txt'), 'utf8'), 'unrelated output\n')
    assert.equal(fs.existsSync(path.join(project, 'themes/sansoul/prebuild/public')), false)
  } finally {
    fs.rmSync(project, { recursive: true, force: true })
  }
})

function run (cwd, command, args, options = {}) {
  // Each fixture owns its lifecycle lock independently of an enclosing check.
  const env = { ...(options.env || process.env) }
  delete env.SANSOUL_LIFECYCLE_TOKEN
  const result = spawnSync(command, args, { cwd, encoding: 'utf8', ...options, env })
  if (!options.allowFailure) assert.equal(result.status, 0, `${command} ${args.join(' ')}\n${result.stdout}\n${result.stderr}`)
  return result
}

function git (cwd, ...args) {
  return run(cwd, 'git', args).stdout.trim()
}

function initializeGit (directory) {
  fs.mkdirSync(directory, { recursive: true })
  git(directory, 'init', '-q', '-b', 'main')
  git(directory, 'config', 'user.name', 'SanSoul fixture')
  git(directory, 'config', 'user.email', 'fixture@example.invalid')
}

function write (root, file, content) {
  const target = path.join(root, file)
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, content)
}

// Fixtures own their wrapper; the consuming project's wrapper may legitimately
// still be the historical themes/sansoul-only version.
function fixtureWrapper (layout) {
  return `#!/bin/sh\nset -eu\ncd "$(dirname "$0")"\nexec sh "./${layout}/do" "$@"\n`
}

function createUpdaterFixture (layout, subsection = 'engine name') {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'sansoul-layout-'))
  const source = path.join(temporary, 'engine-source')
  const project = path.join(temporary, 'consumer space')
  initializeGit(source)
  for (const script of scripts) {
    write(source, `scripts/${script}`, fs.readFileSync(path.join(sourceEngine, 'scripts', script)))
  }
  write(source, 'do', fs.readFileSync(path.join(sourceEngine, 'do')))
  write(source, 'scripts/check-cms-config.js', '// The updater fixture has no CMS output.\n')
  write(source, 'package.json', '{"name":"fixture-engine","type":"module","version":"7.7.0"}\n')
  write(source, 'MIGRATIONS.md', '# Migrations\n\n## 7.7.0\n\nCompatible engine layouts.\n')
  write(source, '.gitignore', 'public\nresources\n.hugo_build.lock\n')
  write(source, 'hugo.default.yml', 'baseURL: http://localhost/\n')
  write(source, 'prebuild/hugo.yml', 'baseURL: http://localhost/\n')
  for (const document of ['README.md', 'AGENTS.md']) {
    write(source, `templates/root/${document}`, `${marker}Engine: {{CORE_PATH}}\n`)
  }
  git(source, 'add', '.')
  git(source, 'commit', '-qm', 'Fixture engine baseline')
  const initial = git(source, 'rev-parse', 'HEAD')

  initializeGit(project)
  git(project, '-c', 'protocol.file.allow=always', 'submodule', 'add', '-q', '--name', subsection, source, layout)
  git(project, 'config', '-f', '.gitmodules', `submodule.${subsection}.branch`, 'main')
  write(project, 'do', fixtureWrapper(layout))
  write(project, 'package.json', JSON.stringify({ name: 'fixture-consumer', type: 'module', version: '7.7.0' }, null, 2) + '\n')
  write(project, '.gitignore', 'node_modules\npublic\nresources\n.hugo_build.lock\n.sansoul-dev.lock\n')
  write(project, 'hugo.yml', 'baseURL: http://localhost/\n')
  write(project, 'data/config.yml', 'config:\n  development: true\n')
  for (const document of ['README.md', 'AGENTS.md']) write(project, document, `${marker}Engine: ${layout}\n`)
  write(project, 'dna/_index.md', '# Fixture DNA\n')
  write(project, 'tracked.txt', 'original\n')
  write(project, 'bin/hugo', `#!/bin/sh
if [ "$1" = version ]; then exit 0; fi
previous=
for argument in "$@"; do
  if [ "$previous" = --destination ]; then
    mkdir -p "$argument"
    printf 'generated: true\\n' > "$argument/hugo.prebuild.yml"
    exit 0
  fi
  previous=$argument
done
mkdir -p public
printf 'built\\n' > public/built.txt
`)
  fs.chmodSync(path.join(project, 'bin/hugo'), 0o755)
  fs.mkdirSync(path.join(project, 'node_modules'))
  git(project, 'add', '.')
  git(project, 'commit', '-qm', 'Fixture consumer baseline')
  write(source, 'revision.txt', 'new revision\n')
  git(source, 'add', '.')
  git(source, 'commit', '-qm', 'Fixture engine fast forward')
  const target = git(source, 'rev-parse', 'HEAD')
  const env = { ...process.env, PATH: `${path.join(project, 'bin')}:${process.env.PATH}` }
  delete env.SANSOUL_LIFECYCLE_TOKEN
  return { temporary, source, project, initial, target, env, engine: path.join(project, layout) }
}

for (const layout of ['core', 'themes/sansoul']) {
  test(`updater resolves subsection by path and validates a clean fast-forward (${layout})`, () => {
    const fixture = createUpdaterFixture(layout)
    try {
      const clone = path.join(fixture.temporary, 'fresh clone')
      git(fixture.temporary, '-c', 'protocol.file.allow=always', 'clone', '-q', '--recurse-submodules', fixture.project, clone)
      assert.equal(git(path.join(clone, layout), 'rev-parse', 'HEAD'), fixture.initial)
      run(clone, 'sh', ['do', 'update', '--check'], { env: fixture.env })
      assert.equal(git(clone, 'status', '--porcelain'), '')
      const check = run(fixture.project, 'sh', ['do', 'update', '--check'], { env: fixture.env })
      assert.match(check.stdout, /Preflight passed/)
      assert.equal(git(fixture.engine, 'rev-parse', 'HEAD'), fixture.initial)
      assert.equal(git(fixture.project, 'status', '--porcelain'), '')
      const update = run(fixture.project, 'sh', ['do', 'update'], { env: fixture.env })
      assert.match(update.stdout, /Update and build completed/)
      assert.equal(git(fixture.engine, 'rev-parse', 'HEAD'), fixture.target)
      assert.equal(fs.readFileSync(path.join(fixture.project, 'public/built.txt'), 'utf8'), 'built\n')
      assert.match(fs.readFileSync(path.join(fixture.project, 'AGENTS.md'), 'utf8'), new RegExp(`Engine: ${layout}`))
      assert.equal(fs.existsSync(path.join(fixture.project, '.sansoul-dev.lock')), false)
      assert.equal(JSON.parse(fs.readFileSync(path.join(fixture.project, 'package.json'))).version, '7.7.0')
      // Restoring the recorded engine requires no gitdir relocation or staging.
      git(fixture.engine, 'checkout', '--detach', fixture.initial)
      assert.equal(git(fixture.project, 'status', '--porcelain'), '')
    } finally {
      fs.rmSync(fixture.temporary, { recursive: true, force: true })
    }
  })

  test(`updater refuses dirty consumer before moving engine (${layout})`, () => {
    const fixture = createUpdaterFixture(layout)
    try {
      write(fixture.project, 'tracked.txt', 'local change\n')
      const result = run(fixture.project, 'sh', ['do', 'update'], { env: fixture.env, allowFailure: true })
      assert.notEqual(result.status, 0)
      assert.match(result.stderr, /project working tree has local changes/)
      assert.equal(git(fixture.engine, 'rev-parse', 'HEAD'), fixture.initial)
      assert.equal(fs.readFileSync(path.join(fixture.project, 'tracked.txt'), 'utf8'), 'local change\n')
      assert.equal(fs.existsSync(path.join(fixture.project, '.sansoul-dev.lock')), false)
    } finally {
      fs.rmSync(fixture.temporary, { recursive: true, force: true })
    }
  })

  test(`8.0 updater migrates selectors and a historical wrapper (${layout})`, () => {
    const fixture = createUpdaterFixture(layout)
    try {
      write(fixture.project, 'do', `#!/bin/sh\nsh ./${layout}/do $1\n`)
      write(fixture.project, 'hugo.yml', `baseURL: https://fixture.example/\nthemesDir: ${path.posix.dirname(layout)}\ntheme: [${path.posix.basename(layout)}]\nparams:\n  owner: fixture\n  domain: fixture.example\n  name: fixture\n`)
      git(fixture.project, 'add', '.')
      git(fixture.project, 'commit', '-qm', 'Fixture historical consumer')
      write(fixture.source, 'package.json', '{"name":"fixture-engine","type":"module","version":"8.0.0","dependencies":{"yaml":"2.9.1"}}\n')
      write(fixture.source, 'MIGRATIONS.md', '# Migrations\n\n## 8.0.0\n\nRun `core/scripts/migrations/8.0.0-project-config.js` and `core/scripts/migrations/8.0.0-markdown-metadata.js` and `core/scripts/migrations/8.0.0-cms-groups.js`.\n\n## 7.7.0\n\nCompatible engine layouts.\n')
      for (const script of ['8.0.0-project-config.js', '8.0.0-markdown-metadata.js', '8.0.0-cms-groups.js']) {
        write(fixture.source, `scripts/migrations/${script}`, fs.readFileSync(path.join(sourceEngine, 'scripts/migrations', script)))
      }
      write(fixture.source, 'assets/js/cms/markdown-metadata.js', fs.readFileSync(path.join(sourceEngine, 'assets/js/cms/markdown-metadata.js')))
      git(fixture.source, 'add', '.')
      git(fixture.source, 'commit', '-qm', 'Fixture 8.0 automatic migrations')
      const before = fs.readFileSync(path.join(fixture.project, 'hugo.yml'), 'utf8')
      // The old $1-only wrapper drops --check; use the engine entry point until
      // the migration has installed the argument-preserving root wrapper.
      run(fixture.project, 'sh', [`${layout}/do`, 'update', '--check'], { env: fixture.env })
      assert.equal(fs.readFileSync(path.join(fixture.project, 'hugo.yml'), 'utf8'), before)
      const update = run(fixture.project, 'sh', ['do', 'update'], { env: fixture.env })
      assert.match(update.stdout, /Migrated project configuration in 2 file/)
      const config = fs.readFileSync(path.join(fixture.project, 'hugo.yml'), 'utf8')
      assert.doesNotMatch(config, /^themes?(?:Dir)?:/m)
      assert.match(config, /domain: fixture.example\n  owner: fixture\n  name: fixture/)
      assert.match(fs.readFileSync(path.join(fixture.project, 'do'), 'utf8'), /if \[ -f .\/core\/do \]/)
      assert.equal(fs.readFileSync(path.join(fixture.project, 'public/built.txt'), 'utf8'), 'built\n')
      assert.equal(JSON.parse(fs.readFileSync(path.join(fixture.project, 'package.json'))).dependencies.yaml, '2.9.1')
      run(fixture.project, 'sh', ['do', 'root-docs'], { env: fixture.env })
      assert.equal(fs.existsSync(path.join(fixture.project, '.sansoul-dev.lock')), false)
    } finally {
      fs.rmSync(fixture.temporary, { recursive: true, force: true })
    }
  })
}

for (const layout of ['core', 'themes/sansoul']) {
  test(`real prebuild resolves project inputs without publishing absolute paths (${layout})`, () => {
    const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'sansoul-prebuild-space-'))
    const project = path.join(temporary, 'consumer space')
    const engine = path.join(project, layout)
    try {
      fs.mkdirSync(engine, { recursive: true })
      for (const relative of ['prebuild', 'data', 'i18n', 'layouts/partials/func']) {
        fs.cpSync(path.join(sourceEngine, relative), path.join(engine, relative), {
          recursive: true,
          filter: source => !source.includes(`${path.sep}public${path.sep}`) && path.basename(source) !== 'public'
        })
      }
      for (const script of ['engine-paths.js', 'prebuild-config.js', 'lifecycle.js', 'video-metadata.js']) {
        write(engine, `scripts/${script}`, fs.readFileSync(path.join(sourceEngine, 'scripts', script)))
      }
      write(engine, 'do', fs.readFileSync(path.join(sourceEngine, 'do')))
      write(engine, 'package.json', '{"type":"module"}\n')
      write(project, 'do', fixtureWrapper(layout))
      write(project, 'hugo.yml', 'baseURL: https://fixture.example/\n')
      fs.cpSync(path.join(sourceEngine, '_examples/data'), path.join(project, 'data'), { recursive: true })
      write(project, 'content/page/_index.es.md', '---\ntitle: Fixture collection title\n---\n')
      // Exercise the root wrapper from outside the consumer as well.
      run(temporary, 'sh', [path.join(project, 'do'), 'prebuild'])
      const config = fs.readFileSync(path.join(engine, 'prebuild/public/hugo.prebuild.yml'), 'utf8')
      for (const suffix of ['assets/u/icons/brands', 'content', 'i18n']) assert.ok(config.includes(`${layout}/${suffix}`))
      assert.ok(config.includes('Fixture collection title'))
      assert.equal(config.includes(temporary), false)
      assert.equal(config.includes('__SANSOUL_'), false)
      assert.match(config, new RegExp(`^themesDir: ${layout === 'core' ? '\\.' : 'themes'}$`, 'm'))
      assert.match(config, new RegExp(`^theme:\\s*\\n\\s*- ${layout === 'core' ? 'core' : 'sansoul'}$`, 'm'))
      assert.equal(fs.readFileSync(path.join(project, 'hugo.yml'), 'utf8'), 'baseURL: https://fixture.example/\n')
      assert.equal(fs.existsSync(path.join(project, '.sansoul-dev.lock')), false)
    } finally {
      fs.rmSync(temporary, { recursive: true, force: true })
    }
  })

  test(`legacy migrations read the executing engine and preserve its sources (${layout})`, () => {
    const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'sansoul-old-migration-'))
    const engine = path.join(temporary, layout)
    try {
      write(engine, 'scripts/engine-paths.js', fs.readFileSync(path.join(sourceEngine, 'scripts/engine-paths.js')))
      for (const script of ['6.0.0-explicit-booleans.js', '6.0.1-sharp.js']) {
        write(engine, `scripts/migrations/${script}`, fs.readFileSync(path.join(sourceEngine, 'scripts/migrations', script)))
      }
      write(engine, 'package.json', '{"type":"module","dependencies":{"sass-embedded":"1.100.0","sharp":"0.35.3"}}\n')
      write(engine, 'hugo.default.yml', 'module:\n  hugoVersion:\n    min: 0.164.0\n')
      write(engine, 'data/keep.yml', 'enabled: y\n')
      write(temporary, 'package.json', '{"type":"module","version":"5.0.0","dependencies":{"sharp":"^0.33.5"}}\n')
      write(temporary, 'data/config.yml', 'enabled: y\ndisabled: n\n')
      for (const script of ['6.0.0-explicit-booleans.js', '6.0.1-sharp.js']) {
        run(temporary, process.execPath, [path.join(engine, 'scripts/migrations', script)])
      }
      assert.equal(fs.readFileSync(path.join(engine, 'data/keep.yml'), 'utf8'), 'enabled: y\n')
      assert.equal(fs.readFileSync(path.join(temporary, 'data/config.yml'), 'utf8'), 'enabled: true\ndisabled: false\n')
      const dependencies = JSON.parse(fs.readFileSync(path.join(temporary, 'package.json'))).dependencies
      assert.equal(dependencies['sass-embedded'], '1.100.0')
      assert.equal(dependencies.sharp, '0.35.3')
    } finally {
      fs.rmSync(temporary, { recursive: true, force: true })
    }
  })
}
