import test from 'node:test'
import assert from 'node:assert/strict'
import { fixture } from './helpers/media-consent-fixture.js'

const flush = async () => { for (let i = 0; i < 12; i++) await Promise.resolve() }


test('comments wait for media consent, remove the embed on revocation and reuse the SDK', async () => {
  const ui = fixture('comments')
  ui.init()
  ui.init()
  ui.intersect()
  await flush()
  assert.equal(ui.listenerCount, 1)
  assert.deepEqual(ui.requests, [])
  assert.equal(ui.notice.hidden, false)
  ui.notice.children[0].click()
  assert.equal(ui.cookieOpens, 1)
  ui.grant(true)
  await flush()
  assert.equal(ui.notice.hidden, true)
  assert.equal(ui.element.childNodes.length, 1)
  ui.grant(false)
  assert.equal(ui.notice.hidden, false)
  assert.equal(ui.element.childNodes.length, 0)
  ui.appendThreadFrame(ui.element)
  ui.mutate()
  assert.equal(ui.element.childNodes.length, 0)
  ui.grant(true)
  await flush()
  assert.equal(ui.resetCalls, 1)
  assert.equal(ui.requests.filter(url => url.endsWith('embed.js')).length, 1)
  assert.equal(ui.element.childNodes.length, 1)
})

