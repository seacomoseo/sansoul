for (const module of ['map', 'form-geo']) {
  test(`${module}: lazy maps do not require consent, and retry after SDK failure`, async () => {
    const ui = fixture(module)
    ui.failSDK()
    ui.init()
    assert.deepEqual(ui.loaded, [])
    assert.equal(ui.notice, undefined)
    assert.equal(ui.element.nextElementSibling, ui.fallback)
    ui.intersect()
    await flush()
    assert.equal(ui.notice.className, 'media-retry')
    assert.equal(ui.notice.children[0].textContent, 'Retry')
    assert.equal(ui.errors.length, 1)
    ui.deferSDK()
    ui.notice.children[0].click()
    await flush()
    ui.grant(false)
    ui.releaseSDK()
    await flush()
    assert.equal(ui.maps.length, 1)
    assert.equal(ui.notice, undefined)
    assert.equal(ui.cookieOpens, 0)
    ui.grant(true)
    ui.grant(false)
    assert.equal(ui.maps[0].removed, false)
    assert.equal(ui.maps.length, 1)
  })
  test(`${module}: disconnected pending component cannot create a map`, async () => {
    const ui = fixture(module)
    ui.grant(true)
    ui.deferSDK()
    ui.init()
    ui.intersect()
    await flush()
    ui.element.isConnected = false
    ui.mutate()
    ui.releaseSDK()
    await flush()
    assert.equal(ui.maps.length, 0)
  })
}

for (const geometry of [
  { type: 'Point', coordinates: [-3, 40] },
  { type: 'Circle', coordinates: [-3, 40], radius: 1200 },
  { type: 'Polygon', coordinates: [[[-3, 40], [-2, 41], [-3, 40]]] }
]) {
  test(`form-geo: preserves ${geometry.type} regardless of consent changes`, async () => {
    const value = JSON.stringify(geometry)
    const ui = fixture('form-geo', { area: geometry.type !== 'Point', saved: value })
    ui.init()
    ui.intersect()
    ui.grant(true)
    await flush()
    ui.grant(false)
    assert.equal(ui.json.value, value)
    ui.grant(true)
    await flush()
    assert.equal(ui.json.value, value)
    if (geometry.type === 'Point') assert.deepEqual([...ui.markers.at(-1).position], [40, -3])
    else {
      assert.equal(ui.groups.at(-1).layers.length, 1)
      if (geometry.type === 'Circle') assert.equal(ui.groups.at(-1).layers[0].radius, 1200)
    }
  })
}

