test('map: removing and reinserting a pending component releases state and can initialize again', async () => {
  const ui = fixture('map')
  ui.failSDK()
  ui.init()
  ui.intersect()
  await flush()
  const oldButton = ui.notice.children[0]
  ui.deferSDK()
  oldButton.click()
  await flush()
  const deliverQueuedIntersection = ui.captureIntersection()
  ui.element.isConnected = false
  ui.mutate()
  ui.releaseSDK()
  await flush()
  assert.equal(ui.maps.length, 0)
  ui.element.isConnected = true
  oldButton.click()
  await flush()
  assert.equal(ui.maps.length, 0, 'the removed state cannot reactivate through its old button')
  ui.init()
  ui.intersect()
  await flush()
  assert.equal(ui.maps.length, 1)
  // A callback captured before disconnect may still be delivered after reinit.
  deliverQueuedIntersection()
  await flush()
  assert.equal(ui.maps.length, 1, 'the retired observer cannot create a second instance')
  assert.equal(ui.listenerCount, 1)
})

