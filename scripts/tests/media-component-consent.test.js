test('comments: replacing a thread releases the old observer ownership and preserves the new active iframe', async () => {
  const ui = fixture('comments')
  ui.init()
  ui.grant(true)
  ui.intersect()
  await flush()
  assert.equal(ui.mutationObserverCount, 2, 'one consent guard and one Disqus guard')
  const next = ui.replaceThread()
  ui.mutate()
  ui.init()
  ui.intersect()
  await flush()
  assert.equal(ui.resetCalls, 1)
  assert.equal(next.childNodes.length, 1)
  ui.mutate()
  ui.mutate()
  assert.equal(next.childNodes.length, 1, 'the old inactive thread cannot remove the new active frame')
  assert.equal(ui.mutationObserverCount, 2, 'replacing the thread does not add a document observer')
  const outside = ui.appendExternalFrame('https://disqus.com/embed/comments/')
  ui.mutate()
  assert.equal(ui.hasExternalFrame(outside), true, 'active thread frames outside the container remain')
  ui.grant(false)
  assert.equal(next.childNodes.length, 0)
  assert.equal(ui.hasExternalFrame(outside), false)
  const late = ui.appendExternalFrame('https://disqus.com/embed/comments/')
  ui.mutate()
  assert.equal(ui.hasExternalFrame(late), false, 'late writes remain guarded after revocation')
})

for (const type of ['Polygon', 'Circle']) {
  test(`form-geo: ${type} creation, editing and deletion synchronize values and conditional fields`, async () => {
    const ui = fixture('form-geo', { area: true })
    ui.init()
    ui.intersect()
    ui.grant(true)
    await flush()
    let coordinates = type === 'Circle' ? [-3, 40] : [[[-3, 40], [-2, 41], [-3, 40]]]
    const layer = { _mRadius: type === 'Circle' ? 1200 : undefined, toGeoJSON: () => ({ geometry: { coordinates } }) }
    const map = ui.maps[0]
    map.events.created({ layer, layerType: type.toLowerCase() })
    assert.deepEqual(JSON.parse(ui.json.value), { type, coordinates, ...(type === 'Circle' ? { radius: 1200 } : {}) })
    const afterCreation = ui.changes.length
    coordinates = type === 'Circle' ? [-4, 41] : [[[-4, 41], [-2, 42], [-4, 41]]]
    map.events['draw:edited']({})
    assert.deepEqual(JSON.parse(ui.json.value).coordinates, coordinates)
    const afterEditing = ui.changes.length
    ui.groups[0].clearLayers()
    map.events['draw:deleted']?.({})
    assert.equal(ui.json.value, '', 'Deleting the area must not submit its previous geometry')
    assert.equal(afterCreation, 1, 'Creating an area must notify conditional form fields')
    assert.equal(afterEditing, 2)
    assert.equal(ui.changes.length, 3)
    assert.ok(ui.changes.every(event => event.type === 'change' && event.bubbles))
    ui.grant(false)
    ui.grant(true)
    await flush()
    assert.equal(ui.json.value, '')
    assert.equal(ui.groups.at(-1).layers.length, 0, 'Reactivation must not restore a deleted area')
  })
}
