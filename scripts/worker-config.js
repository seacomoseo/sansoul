#!/usr/bin/env node

/*
Purpose: Generate the project Worker (entry + Wrangler config) from hugo.yml and
  the build outputs, so consumers keep no worker.js or wrangler TOML.
Run from: A consumer root, after `sh do build`.
Usage: node core/scripts/worker-config.js [--resolve]
  --resolve  Use CLOUDFLARE_API_TOKEN to pick the account (the only one the token
             sees, or CLOUDFLARE_ACCOUNT_ID) and find or create this project's own
             D1/KV by name (<worker>-forms, <worker>-files, <worker>-commerce).
             Without it, local placeholder IDs serve `wrangler dev`.
Writes: worker/entry.generated.js and worker/wrangler.jsonc (both generated, ignored).
Prints: JSON { worker, account, databases, subdomain } for the CI runner.
*/
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { readProject } from './project.js'
import { relativeEnginePath } from './engine-paths.js'

const API = 'https://api.cloudflare.com/client/v4'
const COMPATIBILITY_DATE = '2025-12-10'
// Forms retry drain; one trigger per Worker (Free allows five per account).
const FORMS_CRON = '*/15 * * * *'

export function planWorker (projectDir = process.cwd(), { core = relativeEnginePath(projectDir) } = {}) {
  const project = readProject(projectDir)
  const forms = hasForms(projectDir)
  const commerce = fs.existsSync(path.join(projectDir, 'functions', '_commerce', 'catalog.generated.js'))
  const databases = []
  const kv = []
  if (forms) {
    databases.push({ binding: 'FORMS_DB', database_name: `${project.worker}-forms`, migrations_dir: `../${core}/forms/migrations` })
    kv.push({ binding: 'FORMS_FILES', title: `${project.worker}-files` })
  }
  if (commerce) databases.push({ binding: 'COMMERCE_DB', database_name: `${project.worker}-commerce`, migrations_dir: `../${core}/commerce/migrations` })
  return { project, core, forms, commerce, databases, kv }
}

export function renderEntry ({ core, forms, commerce }) {
  const lines = ['// Generated by core/scripts/worker-config.js from hugo.yml. Do not edit.']
  if (forms) {
    lines.push(`import { createFormsWorker } from '../${core}/forms/worker.js'`)
    lines.push("import { manifest } from './forms.generated.js'")
  }
  if (commerce) {
    lines.push(`import { createCommerceWorker } from '../${core}/commerce/worker.js'`)
    lines.push("import { catalog } from '../functions/_commerce/catalog.generated.js'")
    for (const [name, file] of commerceRoutes) lines.push(`import { onRequest as ${name} } from '../functions/api/commerce/${file}'`)
  }
  lines.push('')
  if (forms) lines.push('const forms = createFormsWorker(manifest)')
  if (commerce) lines.push(`const commerce = createCommerceWorker(catalog, { ${commerceRoutes.map(([name]) => name).join(', ')} })`)
  lines.push('', 'export default {', '  fetch (request, env, ctx) {')
  if (forms) lines.push("    if (new URL(request.url).pathname.startsWith('/api/forms/')) return forms.fetch(request, env, ctx)")
  lines.push(commerce ? '    return commerce.fetch(request, env, ctx)' : '    return env.ASSETS.fetch(request)')
  lines.push(forms ? '  },\n  scheduled: forms.scheduled\n}' : '  }\n}')
  return lines.join('\n') + '\n'
}

const commerceRoutes = [
  ['checkout', 'checkout.js'],
  ['quote', 'quote.js'],
  ['webhook', 'webhook.js'],
  ['status', 'status/[orderId].js'],
  ['admin', 'admin/[[path]].js']
]

export function renderConfig (plan, { account = '', ids = {} } = {}) {
  const { project, forms, commerce, databases, kv } = plan
  const runFirst = [...(forms ? ['/api/forms/*'] : []), ...(commerce ? ['/api/commerce/*'] : [])]
  const config = {
    name: project.worker,
    ...(account ? { account_id: account } : {}),
    compatibility_date: COMPATIBILITY_DATE,
    workers_dev: true,
    preview_urls: false,
    ...(runFirst.length ? { main: 'entry.generated.js' } : {}),
    assets: {
      directory: '../public',
      ...(runFirst.length ? { binding: 'ASSETS', run_worker_first: runFirst } : {}),
      not_found_handling: '404-page'
    },
    vars: Object.fromEntries(Object.entries(project.workerVars).map(([key, value]) => [key, String(value)])),
    d1_databases: databases.map(db => ({ ...db, database_id: ids[db.database_name] || `local-${db.database_name}` })),
    kv_namespaces: kv.map(({ binding, title }) => ({ binding, id: ids[title] || `local-${title}` })),
    ...(forms ? { triggers: { crons: [FORMS_CRON] } } : {})
  }
  return '// Generated by core/scripts/worker-config.js from hugo.yml. Workers Free only; do not edit.\n' +
    JSON.stringify(config, null, 2) + '\n'
}

export async function resolveResources (plan, { token, account, fetch = globalThis.fetch }) {
  const call = async (method, route, body) => {
    const response = await fetch(`${API}${route}`, {
      method,
      headers: { authorization: `Bearer ${token}`, ...(body ? { 'content-type': 'application/json' } : {}) },
      body: body ? JSON.stringify(body) : undefined
    })
    const data = await response.json().catch(() => ({}))
    if (!response.ok || data.success === false) {
      const reason = (data.errors || []).map(error => `${error.code} ${error.message}`).join('; ') || `HTTP ${response.status}`
      throw new Error(`Cloudflare ${method} ${route.split('?')[0]}: ${reason}`)
    }
    return data
  }
  if (!account) {
    const { result } = await call('GET', '/accounts?per_page=50')
    if (result.length !== 1) throw new Error(`The token sees ${result.length} Cloudflare accounts; set CLOUDFLARE_ACCOUNT_ID.`)
    account = result[0].id
  }
  const ids = {}
  const created = []
  for (const db of plan.databases) {
    const { result } = await call('GET', `/accounts/${account}/d1/database?name=${encodeURIComponent(db.database_name)}&per_page=100`)
    let found = result.find(item => item.name === db.database_name)
    if (!found) {
      found = (await call('POST', `/accounts/${account}/d1/database`, { name: db.database_name })).result
      created.push(db.database_name)
    }
    ids[db.database_name] = found.uuid
  }
  if (plan.kv.length) {
    const namespaces = []
    for (let page = 1; ; page++) {
      const { result, result_info: info } = await call('GET', `/accounts/${account}/storage/kv/namespaces?per_page=100&page=${page}`)
      namespaces.push(...result)
      if (!info || page >= (info.total_pages || 1)) break
    }
    for (const { title } of plan.kv) {
      let found = namespaces.find(item => item.title === title)
      if (!found) {
        found = (await call('POST', `/accounts/${account}/storage/kv/namespaces`, { title })).result
        created.push(title)
      }
      ids[title] = found.id
    }
  }
  const subdomain = (await call('GET', `/accounts/${account}/workers/subdomain`)).result?.subdomain || ''
  return { account, ids, created, subdomain }
}

function hasForms (projectDir) {
  const file = path.join(projectDir, 'worker', 'forms.generated.js')
  if (!fs.existsSync(file)) return false
  // An empty manifest (no `action: worker` form) needs no backend bindings.
  return !/"forms":\s*\{\s*\}/.test(fs.readFileSync(file, 'utf8'))
}

async function main () {
  const projectDir = process.cwd()
  const plan = planWorker(projectDir)
  let resolved = { account: process.env.CLOUDFLARE_ACCOUNT_ID || '', ids: {}, created: [], subdomain: '' }
  if (process.argv.includes('--resolve')) {
    const token = process.env.CLOUDFLARE_API_TOKEN
    if (!token) throw new Error('--resolve needs CLOUDFLARE_API_TOKEN.')
    resolved = await resolveResources(plan, { token, account: resolved.account })
  }
  const dir = path.join(projectDir, 'worker')
  fs.mkdirSync(dir, { recursive: true })
  const entry = path.join(dir, 'entry.generated.js')
  if (plan.forms || plan.commerce) fs.writeFileSync(entry, renderEntry(plan))
  else fs.rmSync(entry, { force: true })
  fs.writeFileSync(path.join(dir, 'wrangler.jsonc'), renderConfig(plan, resolved))
  console.log(JSON.stringify({
    worker: plan.project.worker,
    account: resolved.account,
    subdomain: resolved.subdomain,
    created: resolved.created,
    databases: plan.databases.map(db => db.binding)
  }))
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch(error => {
    console.error(`worker config: ${error.message}`)
    process.exit(1)
  })
}
