#!/usr/bin/env node

/*
Purpose: Publish the optional Netlify mirror (params.netlify) of a SanSoul
  project: the same built `public/` on Netlify, with /api/* proxied to the
  project Worker through a signed rewrite (see edge/proxy.js).
Run from: A consumer root, from core/ci/run (after the build and
  `worker-config.js --resolve`).
Usage:
  node core/scripts/netlify-mirror.js check
      Prints `deploy` or `skip` (with the reason on stderr): used by the
      scheduled catch-up run before it spends minutes building.
  node core/scripts/netlify-mirror.js deploy <worker.json>
      Creates the Netlify site if missing (no Git link), sets the proxy secret
      once on both sides, writes netlify.toml in a clean staging folder and
      runs `netlify deploy --prod --no-build` with a pinned CLI.
Environment: NETLIFY_AUTH_TOKEN, CLOUDFLARE_API_TOKEN, GITHUB_SHA (optional).
Credits (Netlify Free: 300 a month, 15 per production deploy): at most one
  deploy an hour and MONTHLY_DEPLOYS a month; a skipped commit is published by
  the next run or the scheduled catch-up.
Secret: SANSOUL_PROXY_SECRET is generated once and never rotated here. Netlify
  reads it on every request; on Free it cannot be a masked secret (the signed
  rewrite needs the post-processing scope), so anyone with access to the
  Netlify site can read it.
*/
import { randomBytes } from 'node:crypto'
import { spawnSync, execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { readProject } from './project.js'

export const NETLIFY_CLI_VERSION = '27.14.2'
export const SECRET_NAME = 'SANSOUL_PROXY_SECRET'
export const MIN_INTERVAL_MS = 60 * 60 * 1000
export const MONTHLY_DEPLOYS = 15
const NETLIFY_API = 'https://api.netlify.com/api/v1'
const CLOUDFLARE_API = 'https://api.cloudflare.com/client/v4'

export function renderNetlifyToml ({ worker, subdomain }) {
  if (!subdomain) throw new Error('The Cloudflare account has no workers.dev subdomain: the mirror cannot reach the Worker.')
  return [
    '# Generated by core/scripts/netlify-mirror.js (SanSoul Netlify mirror). Do not edit.',
    '[[redirects]]',
    'from = "/api/*"',
    `to = "https://${worker}.${subdomain}.workers.dev/api/:splat"`,
    'status = 200',
    'force = true',
    `signed = "${SECRET_NAME}"`,
    ''
  ].join('\n')
}

// Deploys are newest first. Budget counts every production deploy of the month
// (failed ones may still cost credits); freshness and throttle use ready ones.
export function deployDecision ({ deploys, sha, now = Date.now(), minInterval = MIN_INTERVAL_MS, monthly = MONTHLY_DEPLOYS }) {
  const production = deploys.filter(deploy => deploy.context === 'production')
  const ready = production.filter(deploy => deploy.state === 'ready')
  const last = ready[0]
  if (sha && last?.title?.includes(sha)) return { deploy: false, reason: `Netlify already serves ${sha.slice(0, 7)}.` }
  if (last) {
    const wait = minInterval - (now - Date.parse(last.created_at))
    if (wait > 0) return { deploy: false, reason: `Last Netlify deploy was under an hour ago; the next run or the scheduled catch-up publishes this commit (in ${Math.ceil(wait / 60000)} min or later).`, throttled: true }
  }
  const month = new Date(now).toISOString().slice(0, 7)
  const used = production.filter(deploy => String(deploy.created_at).startsWith(month)).length
  if (used >= monthly) return { deploy: false, reason: `Monthly Netlify deploy budget reached (${used}/${monthly}); publish manually or wait for next month.`, throttled: true }
  return { deploy: true, reason: `Deploy ${used + 1}/${monthly} this month.` }
}

function client (base, token, fetchImpl, label) {
  return async (method, route, body, { allow404 = false } = {}) => {
    const response = await fetchImpl(`${base}${route}`, {
      method,
      headers: { authorization: `Bearer ${token}`, ...(body ? { 'content-type': 'application/json' } : {}) },
      body: body ? JSON.stringify(body) : undefined
    })
    if (allow404 && response.status === 404) return null
    const data = await response.json().catch(() => ({}))
    if (!response.ok || data?.success === false) {
      const reason = data?.message || (data?.errors || []).map(error => `${error.code} ${error.message}`).join('; ') || `HTTP ${response.status}`
      throw new Error(`${label} ${method} ${route.split('?')[0]}: ${reason}`)
    }
    return data
  }
}

export async function findSite (name, { token, fetch = globalThis.fetch, create = false }) {
  const netlify = client(NETLIFY_API, token, fetch, 'Netlify')
  const sites = await netlify('GET', `/sites?name=${encodeURIComponent(name)}&filter=all&per_page=100`)
  let site = sites.find(item => item.name === name)
  if (!site && create) site = await netlify('POST', '/sites', { name })
  // Free sites get a «Powered by Netlify» script injected unless this is off.
  if (site && create && site.built_with_badge_enabled !== false) site = await netlify('PATCH', `/sites/${site.id}`, { built_with_badge_enabled: false })
  return site || null
}

export async function listDeploys (siteId, { token, fetch = globalThis.fetch }) {
  const netlify = client(NETLIFY_API, token, fetch, 'Netlify')
  const deploys = await netlify('GET', `/sites/${siteId}/deploys?per_page=100`)
  return deploys.sort((a, b) => Date.parse(b.created_at) - Date.parse(a.created_at))
}

// The Netlify value is the source; the Worker only receives it when it lacks
// the secret or the Netlify value was just created.
export async function syncSecret ({ site, worker, account, netlifyToken, cloudflareToken, fetch = globalThis.fetch, generate = () => randomBytes(32).toString('hex') }) {
  const netlify = client(NETLIFY_API, netlifyToken, fetch, 'Netlify')
  const cloudflare = client(CLOUDFLARE_API, cloudflareToken, fetch, 'Cloudflare')
  const query = `?site_id=${encodeURIComponent(site.id)}`
  const existing = await netlify('GET', `/accounts/${site.account_id}/env/${SECRET_NAME}${query}`, undefined, { allow404: true })
  let value = existing?.values?.find(item => item.context === 'all' || item.context === 'production')?.value || ''
  let created = false
  if (!value) {
    value = generate()
    await netlify('POST', `/accounts/${site.account_id}/env${query}`, [{ key: SECRET_NAME, values: [{ value, context: 'all' }] }])
    created = true
  }
  if (value.length < 32) throw new Error(`Netlify ${SECRET_NAME} is shorter than 32 characters: delete it and rerun to generate a new one.`)
  const { result } = await cloudflare('GET', `/accounts/${account}/workers/scripts/${worker}/secrets`)
  const workerHasSecret = result.some(item => item.name === SECRET_NAME)
  if (created || !workerHasSecret) {
    await cloudflare('PUT', `/accounts/${account}/workers/scripts/${worker}/secrets`, { name: SECRET_NAME, text: value, type: 'secret_text' })
  }
  return { netlifyCreated: created, workerUpdated: created || !workerHasSecret }
}

function currentSha (projectDir) {
  if (process.env.GITHUB_SHA) return process.env.GITHUB_SHA
  try { return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: projectDir, encoding: 'utf8' }).trim() } catch { return '' }
}

async function main () {
  const [command, workerFile] = process.argv.slice(2)
  const projectDir = process.cwd()
  const project = readProject(projectDir)
  const token = process.env.NETLIFY_AUTH_TOKEN
  if (!project.netlify || !token) {
    if (project.netlify) console.log('::warning::params.netlify is set but the NETLIFY_AUTH_TOKEN secret is missing: Netlify mirror skipped.')
    if (command === 'check') console.log('skip')
    return
  }
  const sha = currentSha(projectDir)

  if (command === 'check') {
    const site = await findSite(project.netlify, { token })
    const decision = site ? deployDecision({ deploys: await listDeploys(site.id, { token }), sha }) : { deploy: true, reason: 'The Netlify site does not exist yet.' }
    console.error(decision.reason)
    console.log(decision.deploy ? 'deploy' : 'skip')
    return
  }
  if (command !== 'deploy' || !workerFile) throw new Error('Usage: netlify-mirror.js check | deploy <worker.json>')

  const resolved = JSON.parse(fs.readFileSync(workerFile, 'utf8'))
  const toml = renderNetlifyToml({ worker: project.worker, subdomain: resolved.subdomain })
  const site = await findSite(project.netlify, { token, create: true })
  const decision = deployDecision({ deploys: await listDeploys(site.id, { token }), sha })
  if (!decision.deploy) {
    console.log(`::${decision.throttled ? 'warning' : 'notice'}::Netlify mirror skipped: ${decision.reason}`)
    return
  }
  const cloudflareToken = process.env.CLOUDFLARE_API_TOKEN
  if (!cloudflareToken) throw new Error('Needs CLOUDFLARE_API_TOKEN to give the Worker the proxy secret.')
  const secret = await syncSecret({ site, worker: project.worker, account: resolved.account, netlifyToken: token, cloudflareToken })
  console.log(`Proxy secret: Netlify ${secret.netlifyCreated ? 'created' : 'kept'}, Worker ${secret.workerUpdated ? 'updated' : 'kept'}.`)

  // Clean staging: only netlify.toml, no functions folder to autodiscover.
  const staging = fs.mkdtempSync(path.join(process.env.RUNNER_TEMP || os.tmpdir(), 'sansoul-netlify-'))
  try {
    fs.writeFileSync(path.join(staging, 'netlify.toml'), toml)
    fs.mkdirSync(path.join(staging, 'no-functions'))
    const args = ['--yes', `netlify-cli@${NETLIFY_CLI_VERSION}`, 'deploy', '--prod', '--no-build',
      '--dir', path.join(projectDir, 'public'), '--functions', path.join(staging, 'no-functions'),
      '--site', site.id, '--message', `SanSoul ${sha || 'local'}`]
    const run = spawnSync('npx', args, { cwd: staging, stdio: 'inherit', env: { ...process.env, NETLIFY_SITE_ID: site.id } })
    if (run.status !== 0) throw new Error(`netlify deploy exited with ${run.status}`)
  } finally {
    fs.rmSync(staging, { recursive: true, force: true })
  }
  console.log(`Netlify mirror: ${site.ssl_url || site.url} (${decision.reason})`)
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch(error => {
    console.error(`netlify mirror: ${error.message}`)
    process.exit(1)
  })
}
