#!/usr/bin/env node

/* `sh do up` and `sh do down` for consumer projects, without external tools.
 *
 * up:   commit everything, rebase onto the remote branch and push.
 * down: bring the remote branch in, keeping uncommitted work in place.
 *
 * Both share one integration path: local work becomes a commit, the commit is
 * rebased onto the remote branch, and conflicts with an obvious answer are
 * resolved here (generated root docs, lockfiles, a fast-forwardable engine
 * pointer). Any other conflict aborts the rebase, so nothing is lost: the work
 * is also pushed to a `local/<date>` rescue branch and a ready-to-paste prompt
 * for an agent is written, printed and copied to the clipboard when possible.
 * Messages are in Spanish because they are read by the project owner. */
import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const MAX_FILE_BYTES = 95 * 1024 * 1024
const LOCKFILES = new Set(['pnpm-lock.yaml', 'package-lock.json'])
const GENERATED_DOCS = new Set(['README.md', 'AGENTS.md', '.github/workflows/sansoul.yml'])
const GENERATED_PREFIXES = ['<!-- Generated by `sh do root-docs`', '# Generated by `sh do root-docs`']
const ENGINE_PATHS = new Set(['core', 'themes/sansoul'])

class SyncError extends Error {}

function pad (number) {
  return String(number).padStart(2, '0')
}

export function stamp (date = new Date(), separator = ' ') {
  const day = `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`
  return `${day}${separator}${pad(date.getHours())}${separator === ' ' ? ':' : ''}${pad(date.getMinutes())}`
}

// "Update: 2026-11-17 13:05 · content/a.md, data/b.yml +3"
export function commitMessage (files, date = new Date()) {
  const shown = files.slice(0, 3).join(', ')
  const rest = files.length > 3 ? ` +${files.length - 3}` : ''
  return `Update: ${stamp(date)}${shown ? ` · ${shown}${rest}` : ''}`
}

function createGit (cwd) {
  const run = (args, { allowFail = false, input } = {}) => {
    const result = spawnSync('git', args, {
      cwd,
      encoding: 'utf8',
      input,
      env: { ...process.env, GIT_EDITOR: 'true', GIT_TERMINAL_PROMPT: '0' }
    })
    if (result.error) throw new SyncError(`No se pudo ejecutar git: ${result.error.message}`)
    if (result.status !== 0 && !allowFail) {
      throw new SyncError(`git ${args.join(' ')} falló:\n${(result.stderr || result.stdout).trim()}`)
    }
    return { ok: result.status === 0, out: result.stdout.trim(), err: result.stderr.trim() }
  }
  return run
}

function defaultRegenerateLock (cwd, lockfile) {
  const command = lockfile === 'pnpm-lock.yaml'
    ? ['pnpm', ['install', '--lockfile-only', '--ignore-scripts']]
    : ['npm', ['install', '--package-lock-only', '--ignore-scripts']]
  const result = spawnSync(command[0], command[1], { cwd, encoding: 'utf8', stdio: 'pipe' })
  return !result.error && result.status === 0
}

function defaultRegenerateDocs (cwd) {
  const result = spawnSync(process.execPath, [path.join(scriptDir, 'root-docs.js')], { cwd, encoding: 'utf8', stdio: 'pipe' })
  return !result.error && result.status === 0
}

function defaultClipboard (text) {
  const candidates = [['pbcopy', []], ['wl-copy', []], ['xclip', ['-selection', 'clipboard']], ['termux-clipboard-set', []]]
  for (const [command, args] of candidates) {
    const result = spawnSync(command, args, { input: text, stdio: ['pipe', 'ignore', 'ignore'] })
    if (!result.error && result.status === 0) return command
  }
  return ''
}

export async function sync (mode, options = {}) {
  const {
    cwd = process.cwd(),
    message = '',
    now = () => new Date(),
    log = text => console.log(text),
    regenerateLock = defaultRegenerateLock,
    regenerateDocs = defaultRegenerateDocs,
    clipboard = defaultClipboard
  } = options
  if (!['up', 'down'].includes(mode)) throw new SyncError(`Modo desconocido: ${mode}`)
  const git = createGit(cwd)

  // Preflight: a named branch with an origin remote and no operation in progress.
  if (!git(['rev-parse', '--is-inside-work-tree'], { allowFail: true }).ok) throw new SyncError('Esto no es un repositorio Git.')
  const gitPath = name => path.resolve(cwd, git(['rev-parse', '--git-path', name]).out)
  // Mid-rebase HEAD is detached; the branch being rebased is still recorded.
  const rebasing = ['rebase-merge', 'rebase-apply'].map(dir => gitPath(`${dir}/head-name`)).find(file => fs.existsSync(file))
  const branch = git(['symbolic-ref', '--short', '-q', 'HEAD'], { allowFail: true }).out ||
    (rebasing ? fs.readFileSync(rebasing, 'utf8').trim().replace(/^refs\/heads\//, '') : '')
  const upstream = `origin/${branch}`
  const remoteUrl = git(['remote', 'get-url', 'origin'], { allowFail: true }).out
  if (!remoteUrl) throw new SyncError('El repositorio no tiene remoto «origin».')
  let wip = false
  const undoWip = () => {
    if (!wip) return
    git(['reset', '-q', 'HEAD~1'])
    wip = false
  }
  const pending = ['rebase-merge', 'rebase-apply', 'MERGE_HEAD', 'CHERRY_PICK_HEAD'].filter(name => fs.existsSync(gitPath(name)))
  if (!branch || pending.length) {
    const reason = pending.length ? `hay una operación de Git a medias (${pending.join(', ')})` : 'el repositorio no está en ninguna rama (HEAD separado)'
    return fail({ reason, files: conflictedFiles(git) })
  }

  for (const engine of ENGINE_PATHS) {
    if (!fs.existsSync(path.join(cwd, engine, '.git'))) continue
    if (git(['-C', engine, 'status', '--porcelain'], { allowFail: true }).out) {
      log(`🟡 ${engine}/ tiene cambios propios: no se suben desde aquí (el motor es otro repositorio).`)
    }
  }

  // Local work becomes one commit (a temporary one for `down`).
  const commit = args => {
    const result = git(['commit', '-q', ...args], { allowFail: true })
    if (result.ok) return
    git(['reset', '-q'])
    const identity = /identity|ident name|user\.email/i.test(result.err)
      ? '\nGit no sabe quién eres. Configúralo una vez: git config --global user.name "Tu nombre" && git config --global user.email "tu@correo"'
      : ''
    throw new SyncError(`No se pudo crear el commit:\n${result.err}${identity}`)
  }
  git(['add', '-A'])
  const staged = git(['diff', '--cached', '--name-only', '-z']).out.split('\0').filter(Boolean)
  if (staged.length) {
    const big = staged.filter(file => {
      const full = path.join(cwd, file)
      return fs.existsSync(full) && fs.statSync(full).isFile() && fs.statSync(full).size > MAX_FILE_BYTES
    })
    if (big.length) {
      git(['reset', '-q'])
      throw new SyncError(`Archivos demasiado grandes para GitHub (>95 MB); sácalos o añádelos a .gitignore:\n  ${big.join('\n  ')}`)
    }
    if (mode === 'up') {
      const text = message || commitMessage(staged, now())
      commit(['-m', text])
      log(`📝 Commit: ${text}`)
    } else {
      commit(['--no-verify', '-m', 'sansoul: temporary commit of local changes (sh do down)'])
      wip = true
      log(`💾 ${staged.length} cambio(s) local(es) guardado(s) temporalmente.`)
    }
  } else if (mode === 'up') {
    log('🤷 No hay cambios nuevos que guardar.')
  }

  for (let attempt = 1; attempt <= 3; attempt++) {
    log('🌐 Consultando el remoto…')
    const fetched = git(['fetch', '-q', 'origin', branch], { allowFail: true })
    const hasUpstream = git(['rev-parse', '--verify', '-q', `refs/remotes/${upstream}`], { allowFail: true }).ok
    if (!fetched.ok && hasUpstream) {
      undoWip()
      throw new SyncError(`No se pudo conectar con el remoto:\n${fetched.err}`)
    }

    if (hasUpstream) {
      const [behind, ahead] = git(['rev-list', '--left-right', '--count', `${upstream}...HEAD`]).out.split(/\s+/).map(Number)
      if (behind && !ahead) {
        git(['merge', '-q', '--ff-only', upstream])
        log(`⬇️  ${behind} cambio(s) del remoto aplicados.`)
      } else if (behind && ahead) {
        log(`🔀 Integrando ${behind} cambio(s) del remoto con ${ahead} local(es)…`)
        const outcome = rebase(git, { cwd, upstream, regenerateLock, regenerateDocs, log })
        if (!outcome.ok) {
          return fail({ reason: 'los cambios locales y los del remoto chocan en los mismos archivos', files: outcome.files, commit: outcome.commit })
        }
      }
    }

    if (mode === 'down') {
      undoWip()
      const unpushed = hasUpstream ? Number(git(['rev-list', '--count', `${upstream}..HEAD`]).out) : 0
      if (unpushed) log(`🟡 Tienes ${unpushed} commit(s) sin subir: usa \`sh do up\`.`)
      log('✅ Proyecto al día.')
      return { ok: true }
    }

    if (hasUpstream && Number(git(['rev-list', '--count', `${upstream}..HEAD`]).out) === 0) {
      log('✅ Nada que subir: el remoto ya tiene todo.')
      return { ok: true }
    }
    const pushed = git(['push', '-q', 'origin', `HEAD:refs/heads/${branch}`], { allowFail: true })
    if (pushed.ok) {
      log('✅ Subido.')
      return { ok: true }
    }
    // Someone pushed in between: integrate again; anything else is a real error.
    if (!/rejected|fetch first|non-fast-forward/i.test(pushed.err)) throw new SyncError(`No se pudo subir:\n${pushed.err}`)
    log('🔁 El remoto cambió mientras subía; reintento.')
  }
  throw new SyncError('El remoto cambia más rápido de lo que se puede subir; inténtalo de nuevo en un momento.')

  function fail ({ reason, files = [], commit = '' }) {
    const date = now()
    let rescue = ''
    let rescuePushed = false
    if (branch && !pending.length) {
      rescue = uniqueBranch(git, `local/${stamp(date, '-')}`)
      git(['branch', rescue, 'HEAD'])
      rescuePushed = git(['push', '-q', 'origin', `${rescue}:refs/heads/${rescue}`], { allowFail: true }).ok
      undoWip()
    }
    const prompt = agentPrompt({ mode, reason, files, commit, branch, upstream, rescue, rescuePushed, remoteUrl, cwd, git })
    const file = gitPath('sansoul-agent-prompt.md')
    fs.writeFileSync(file, prompt)
    const copied = clipboard(prompt)
    log(`\n❌ No se ha podido terminar: ${reason}.`)
    if (rescue) log(`💾 Nada se ha perdido: tu trabajo está también en la rama ${rescue}${rescuePushed ? ' (subida al remoto)' : ' (solo local: no se pudo subir)'}.`)
    log(`🤖 Pásale este encargo a un agente${copied ? ' (ya está en el portapapeles)' : ''}; también está en ${path.relative(cwd, file)}:\n`)
    log(prompt)
    return { ok: false, rescue, rescuePushed, prompt, promptFile: file, files }
  }
}

function conflictedFiles (git) {
  return git(['diff', '--name-only', '--diff-filter=U'], { allowFail: true }).out.split('\n').filter(Boolean)
}

function uniqueBranch (git, base) {
  let name = base
  for (let index = 2; git(['rev-parse', '--verify', '-q', `refs/heads/${name}`], { allowFail: true }).ok; index++) name = `${base}-${index}`
  return name
}

function rebase (git, { cwd, upstream, regenerateLock, regenerateDocs, log }) {
  let docs = false
  let step = git(['rebase', '-q', upstream], { allowFail: true })
  while (!step.ok) {
    const files = conflictedFiles(git)
    const commit = git(['log', '-1', '--format=%h %s', 'REBASE_HEAD'], { allowFail: true }).out
    if (!files.length) {
      git(['rebase', '--abort'], { allowFail: true })
      return { ok: false, files, commit }
    }
    const lockfiles = []
    for (const file of files) {
      const kind = resolveSafely(git, cwd, file)
      if (!kind) {
        git(['rebase', '--abort'], { allowFail: true })
        return { ok: false, files, commit }
      }
      if (kind === 'lock') lockfiles.push(file)
      if (kind === 'docs') docs = true
      log(`🧩 Resuelto automáticamente: ${file}`)
    }
    for (const lockfile of lockfiles) {
      if (!regenerateLock(cwd, lockfile)) {
        git(['rebase', '--abort'], { allowFail: true })
        return { ok: false, files, commit }
      }
      git(['add', '--', lockfile])
    }
    step = git(['rebase', '--continue'], { allowFail: true })
    // An empty step (the remote already had the same change) is skipped.
    if (!step.ok && !conflictedFiles(git).length && /nothing to commit|no changes|empty/i.test(step.out + step.err)) {
      step = git(['rebase', '--skip'], { allowFail: true })
    }
  }
  if (docs && regenerateDocs(cwd)) {
    git(['add', '--', ...[...GENERATED_DOCS].filter(file => fs.existsSync(path.join(cwd, file)))])
    if (!git(['diff', '--cached', '--quiet'], { allowFail: true }).ok) git(['commit', '-q', '-m', 'Regenerate root docs'])
  }
  return { ok: true }
}

// During a rebase, stage 2 ("ours") is the remote side and stage 3 the local one.
function resolveSafely (git, cwd, file) {
  const stages = Object.fromEntries(git(['ls-files', '-u', '--', file]).out.split('\n').filter(Boolean).map(line => {
    const [meta] = line.split('\t')
    const [mode, sha, stage] = meta.split(' ')
    return [stage, { mode, sha }]
  }))
  const remote = stages['2']
  const local = stages['3']
  if (!remote || !local) return ''

  if (ENGINE_PATHS.has(file) && remote.mode === '160000' && local.mode === '160000') {
    const engine = ['-C', file]
    const has = sha => git([...engine, 'cat-file', '-e', `${sha}^{commit}`], { allowFail: true }).ok
    if (!has(remote.sha) || !has(local.sha)) git([...engine, 'fetch', '-q', 'origin'], { allowFail: true })
    if (!has(remote.sha) || !has(local.sha)) return ''
    const newer = git([...engine, 'merge-base', '--is-ancestor', remote.sha, local.sha], { allowFail: true }).ok
      ? local.sha
      : git([...engine, 'merge-base', '--is-ancestor', local.sha, remote.sha], { allowFail: true }).ok ? remote.sha : ''
    if (!newer) return ''
    git(['update-index', '--cacheinfo', `160000,${newer},${file}`])
    git([...engine, 'checkout', '-q', newer], { allowFail: true })
    return 'engine'
  }

  if (LOCKFILES.has(file)) {
    git(['checkout', '--ours', '--', file])
    git(['add', '--', file])
    return 'lock'
  }

  if (GENERATED_DOCS.has(file)) {
    const content = git(['show', `:2:${file}`]).out
    if (!GENERATED_PREFIXES.some(prefix => content.startsWith(prefix))) return ''
    git(['checkout', '--ours', '--', file])
    git(['add', '--', file])
    return 'docs'
  }
  return ''
}

function agentPrompt ({ mode, reason, files, commit, branch, upstream, rescue, rescuePushed, remoteUrl, cwd, git }) {
  const project = path.basename(cwd)
  const head = git(['rev-parse', '--short', 'HEAD'], { allowFail: true }).out
  const remoteHead = git(['rev-parse', '--short', upstream], { allowFail: true }).out
  const list = files.length ? files.map(file => `- \`${file}\``).join('\n') : '- (Git no informó de archivos concretos)'
  const steps = rescue
    ? [
        `git fetch origin ${branch}${rescuePushed ? ` ${rescue}` : ''}`,
        `git switch ${branch}`,
        `git reset --hard origin/${branch}   # solo si el trabajo local está a salvo en ${rescue}`,
        `git merge ${rescuePushed ? `origin/${rescue}` : rescue}   # resolver aquí los conflictos`,
        'sh do build',
        `git push origin ${branch}`,
        rescuePushed ? `git push origin --delete ${rescue} && git branch -D ${rescue}` : `git branch -D ${rescue}`
      ]
    : ['git status', 'git rebase --abort   # o --continue si ya está resuelto', 'sh do up']
  return `# Resolver conflicto de Git en ${project}

Contexto: \`sh do ${mode}\` del proyecto SanSoul \`${project}\` no ha podido terminar porque ${reason}.

- Repositorio: ${remoteUrl}
- Rama: \`${branch || '(ninguna)'}\` · local \`${head}\` · remoto \`${remoteHead || '?'}\`
${rescue ? `- Copia del trabajo local: rama \`${rescue}\`${rescuePushed ? ' (en el remoto)' : ' (solo en este equipo)'}\n` : ''}${commit ? `- Commit local que choca: ${commit}\n` : ''}
Archivos en conflicto:
${list}

Objetivo: integrar el trabajo local con el del remoto en \`${branch}\` sin perder nada de ninguno de los dos lados. Si un mismo dato cambió en ambos y no está claro cuál vale, pregunta antes de elegir.

Pasos sugeridos (desde la raíz del proyecto):
\`\`\`sh
${steps.join('\n')}
\`\`\`

Al terminar: \`sh do build\` sin errores, \`${branch}\` subida, la rama de copia borrada y \`git status\` limpio. Lee antes \`AGENTS.md\` del proyecto.
`
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [mode, ...rest] = process.argv.slice(2)
  try {
    const result = await sync(mode, { message: rest.join(' ').trim() })
    if (!result.ok) process.exitCode = 1
  } catch (error) {
    if (!(error instanceof SyncError)) throw error
    console.error(`❌ ${error.message}`)
    process.exitCode = 1
  }
}
