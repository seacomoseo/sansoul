// Collect the per-form policies Hugo published in public/_forms/ into the
// private Worker manifest and remove them from the deployable assets.
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { formKey, MANIFEST_VERSION, validateManifest } from '../manifest.js'

export function buildManifest ({ root = process.cwd(), publicDir = 'public', out = 'worker/forms.generated.js' } = {}) {
  const source = resolve(root, publicDir, '_forms')
  if (!existsSync(source)) return null
  const forms = {}
  const specs = {}
  let site = ''
  for (const name of readdirSync(source).filter(file => file.endsWith('.json')).sort()) {
    const { page, site: domain, ...spec } = JSON.parse(readFileSync(join(source, name), 'utf8'))
    site ||= domain || ''
    const ref = createHash('sha256').update(JSON.stringify(spec)).digest('hex').slice(0, 16)
    specs[ref] = spec
    forms[formKey(page, spec.id)] = ref
  }
  const manifest = validateManifest({ version: MANIFEST_VERSION, site, forms, specs })
  const target = resolve(root, out)
  mkdirSync(resolve(target, '..'), { recursive: true })
  writeFileSync(target, `// Generated by core/forms/scripts/build-manifest.js. Do not edit or publish.\nexport const manifest = ${JSON.stringify(manifest, null, 2)}\n`)
  rmSync(source, { recursive: true, force: true })
  return { forms: Object.keys(forms).length, specs: Object.keys(specs).length, target }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const result = buildManifest()
    if (result) console.log(`forms manifest: ${result.forms} forms, ${result.specs} policies → ${result.target}`)
  } catch (error) {
    console.error(`forms manifest: ${error.message}`)
    process.exit(1)
  }
}
